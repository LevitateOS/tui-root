#!/usr/bin/env bun
/**
 * Writes src/domain/land.ts: where there is land, as a small bitmap the time zone map
 * draws from. Run it with Natural Earth's 1:110m land polygons (public domain):
 *
 *   bun scripts/land-mask.ts ne_110m_land.geojson
 *
 * https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_land.geojson
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** The bitmap's size and the latitudes it spans; the poles are left out. */
const WIDTH = 160;
const HEIGHT = 72;
const NORTH = 78;
const SOUTH = -56;

type Ring = [number, number][];
const source = process.argv[2];
if (!source) throw new Error("usage: bun scripts/land-mask.ts ne_110m_land.geojson");
const land = JSON.parse(readFileSync(source, "utf8")) as {
	features: { geometry: { type: string; coordinates: Ring[] | Ring[][] } }[];
};
const rings: Ring[] = land.features.flatMap(({ geometry }) =>
	geometry.type === "Polygon"
		? (geometry.coordinates as Ring[])
		: (geometry.coordinates as Ring[][]).flat(),
);

/** Even-odd over every ring, so a hole (a ring inside a ring) is water. */
function isLand(lon: number, lat: number): boolean {
	let inside = false;
	for (const ring of rings) {
		for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
			const [x1, y1] = ring[i]!;
			const [x2, y2] = ring[j]!;
			if (y1 > lat !== y2 > lat && lon < ((x2 - x1) * (lat - y1)) / (y2 - y1) + x1) inside = !inside;
		}
	}
	return inside;
}

const rows: string[] = [];
for (let y = 0; y < HEIGHT; y++) {
	const lat = NORTH - ((y + 0.5) / HEIGHT) * (NORTH - SOUTH);
	let hex = "";
	for (let x = 0; x < WIDTH; x += 4) {
		let nibble = 0;
		for (let bit = 0; bit < 4; bit++) {
			const lon = -180 + ((x + bit + 0.5) / WIDTH) * 360;
			if (isLand(lon, lat)) nibble |= 8 >> bit;
		}
		hex += nibble.toString(16);
	}
	rows.push(hex);
}

writeFileSync(
	join(import.meta.dir, "../src/domain/land.ts"),
	`// Generated by scripts/land-mask.ts from Natural Earth's 1:110m land polygons (public
// domain). Do not edit: run the script again.

/** The bitmap's size, and the latitudes its first and last rows are at. */
export const LAND_WIDTH = ${WIDTH};
export const LAND_HEIGHT = ${HEIGHT};
export const LAND_NORTH = ${NORTH};
export const LAND_SOUTH = ${SOUTH};

/** One row a string, west to east from 180°W: each hex digit is four cells, its high bit
 * the westmost; a set bit is land. */
const ROWS = [
${rows.map((row) => `\t"${row}",`).join("\n")}
] as const;

/** Whether the place is land, as far as a ${WIDTH} by ${HEIGHT} bitmap knows. */
export function isLand(lat: number, lon: number): boolean {
	const y = Math.floor(((LAND_NORTH - lat) / (LAND_NORTH - LAND_SOUTH)) * LAND_HEIGHT);
	const x = Math.floor(((((lon + 180) % 360) + 360) % 360) / 360 * LAND_WIDTH);
	const row = ROWS[y];
	if (row === undefined) return false;
	return (Number.parseInt(row[x >> 2]!, 16) & (8 >> (x & 3))) !== 0;
}
`,
);
console.log(`land.ts: ${WIDTH}x${HEIGHT}, ${rows.join("").length} hex digits`);
